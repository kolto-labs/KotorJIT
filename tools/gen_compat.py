#!/usr/bin/env python3
"""Generate the dual-dialect alias and event tables from data/api_aliases.toml.

Scripts for this kind of runtime were written against one of two Halo server
mods that never agreed on names -- `readbyte` versus `read_byte`, `say` versus
`say_all`. People currently bridge that with a compatibility module written in
Lua, which costs a table lookup on every call and breaks when either side moves.

Both dialects are native here instead, so the bridging happens once at
registration rather than on every call.

Emits:
    src/generated/compat_aliases.inc   alias -> canonical, with dialect
    src/generated/compat_events.inc    SAPP event constant -> our event name
    docs/api-dialects.md               the reference for script authors
"""
from __future__ import annotations

import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "api_aliases.toml"
GEN = ROOT / "src" / "generated"
DOCS = ROOT / "docs" / "api-dialects.md"

BANNER = ("// Generated by tools/gen_compat.py from data/api_aliases.toml.\n"
          "// Do not edit; edit the table and regenerate.\n")


def load() -> dict:
    with SRC.open("rb") as fh:
        doc = tomllib.load(fh)

    problems = []
    seen = {}
    for a in doc.get("alias", []):
        for k in ("canonical", "alias", "dialect"):
            if not a.get(k):
                problems.append(f"alias entry missing {k}: {a}")
        if a["alias"] in seen and seen[a["alias"]] != a["canonical"]:
            problems.append(f"{a['alias']} aliases both {seen[a['alias']]} "
                            f"and {a['canonical']}")
        seen[a["alias"]] = a["canonical"]
        if a["alias"] == a["canonical"]:
            problems.append(f"{a['alias']} aliases itself")
    names = set()
    for e in doc.get("event_alias", []):
        if not e.get("sapp"):
            problems.append(f"event entry with no constant: {e}")
        if e["sapp"] in names:
            problems.append(f"duplicate event constant {e['sapp']}")
        names.add(e["sapp"])
    if problems:
        for p in problems:
            print(f"error: {p}", file=sys.stderr)
        raise SystemExit(1)
    return doc


def gen_aliases(doc: dict) -> str:
    out = [BANNER, "// clang-format off"]
    for a in doc["alias"]:
        out.append(f'{{"{a["alias"]}", "{a["canonical"]}", "{a["dialect"]}"}},')
    out.append("// clang-format on")
    return "\n".join(out) + "\n"


def gen_events(doc: dict) -> str:
    out = [BANNER, "// clang-format off"]
    for i, e in enumerate(doc["event_alias"]):
        lua = e.get("lua_name") or ""
        note = (e.get("note") or "").replace('"', "'")
        out.append(f'{{"{e["sapp"]}", "{lua}", {i}, "{note}"}},')
    out.append("// clang-format on")
    return "\n".join(out) + "\n"


def gen_docs(doc: dict) -> str:
    aliases = doc["alias"]
    events = doc["event_alias"]
    mapped = [e for e in events if e.get("lua_name")]
    unmapped = [e for e in events if not e.get("lua_name")]

    by_canon: dict[str, list[dict]] = {}
    for a in aliases:
        by_canon.setdefault(a["canonical"], []).append(a)

    L = ["# Two ways to write the same script", "",
         "Generated from `data/api_aliases.toml`. Do not edit by hand.", "",
         "Scripts for this kind of runtime came from one of two Halo server mods, and",
         "the two never agreed on names. One writes `readbyte`, `getplayer`, `say`; the",
         "other writes `read_byte`, `get_player`, `say_all`. Both work here, natively.",
         "Mixing them in one file is fine.", "",
         "You do not need a compatibility module. There isn't one to require.", "",
         f"**{len(aliases)} aliases** over **{len(by_canon)} functions**.", "",
         "## Names", "",
         "| this runtime calls it | also accepts |",
         "|---|---|"]
    for canon in sorted(by_canon):
        alts = ", ".join(f"`{a['alias']}`" for a in by_canon[canon])
        L.append(f"| `{canon}` | {alts} |")

    L += ["", "## Events, two ways", "",
          "Define a global and it is found at load:", "",
          "```lua", "function OnTick(tick, relevant)", "    -- ...", "end", "```", "",
          "Or register a handler by name at runtime:", "",
          "```lua", 'function OnScriptLoad(game, build)',
          '    register_callback(cb.EVENT_TICK, "my_tick")', "end", "",
          "function my_tick(tick, relevant)", "    -- ...", "end", "```", "",
          "A runtime registration wins over a same-named global, since asking for one",
          "is explicit. `unregister_callback(cb.EVENT_TICK)` removes it.", "",
          f"### The {len(mapped)} events that map", "",
          "| constant | raises |", "|---|---|"]
    for e in mapped:
        L.append(f"| `cb.{e['sapp']}` | `{e['lua_name']}` |")

    L += ["", f"### The {len(unmapped)} that do not", "",
          "These are Halo concepts. A single-player RPG has no teams, no vehicles and no",
          "network players, so there is nothing honest to bind them to. The constants",
          "exist so a script referencing one still loads, and registering for one logs",
          "once saying it will never fire rather than failing silently.", "",
          "| constant | why |", "|---|---|"]
    for e in unmapped:
        L.append(f"| `cb.{e['sapp']}` | {e.get('note') or 'not yet mapped'} |")
    L.append("")
    return "\n".join(L)


def main() -> int:
    doc = load()
    GEN.mkdir(parents=True, exist_ok=True)
    (GEN / "compat_aliases.inc").write_text(gen_aliases(doc))
    (GEN / "compat_events.inc").write_text(gen_events(doc))
    DOCS.write_text(gen_docs(doc))

    mapped = sum(1 for e in doc["event_alias"] if e.get("lua_name"))
    canon = len({a["canonical"] for a in doc["alias"]})
    print(f"{len(doc['alias'])} aliases over {canon} functions, "
          f"{len(doc['event_alias'])} event constants ({mapped} mapped) "
          f"-> compat_aliases.inc, compat_events.inc, docs/api-dialects.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
