#!/usr/bin/env python3
"""Generate host-name aliases and the cb event table.

Canonical names are what the C modules and the Odyssey corpus register:
kotor.mem.readbyte, kotor.GetFirstPC, kotor.SendMessageToPC. Scripts may also
write the underscored form. Both spellings point at the same C function.

Event constants come from data/events.toml lua_name values, which were derived
from the decompiled dispatch (OnModulePlayerEnter, OnTick, OnCreatureDeath).
There is no Halo getplayer(0..15) or EVENT_JOIN surface.

Emits:
    src/generated/compat_aliases.inc   alias -> canonical
    src/generated/compat_events.inc    cb constant -> event name
    docs/api-dialects.md               the reference for script authors
"""
from __future__ import annotations

import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "api_aliases.toml"
EVENTS_SRC = ROOT / "data" / "events.toml"
GEN = ROOT / "src" / "generated"
DOCS = ROOT / "docs" / "api-dialects.md"

BANNER_ALIASES = (
    "// Generated by tools/gen_compat.py from data/api_aliases.toml.\n"
    "// Do not edit; edit the table and regenerate.\n"
)
BANNER_EVENTS = (
    "// Generated by tools/gen_compat.py from data/api_aliases.toml "
    "and data/events.toml.\n"
    "// Do not edit; edit the tables and regenerate.\n"
)


def event_constant(e: dict) -> str:
    return e.get("constant") or e.get("sapp") or ""


def load_aliases() -> dict:
    with SRC.open("rb") as fh:
        doc = tomllib.load(fh)

    problems = []
    seen = {}
    for a in doc.get("alias", []):
        for k in ("canonical", "alias", "dialect"):
            if not a.get(k):
                problems.append(f"alias entry missing {k}: {a}")
        if a["alias"] in seen and seen[a["alias"]] != a["canonical"]:
            problems.append(f"{a['alias']} aliases both {seen[a['alias']]} "
                            f"and {a['canonical']}")
        seen[a["alias"]] = a["canonical"]
        if a["alias"] == a["canonical"]:
            problems.append(f"{a['alias']} aliases itself")
    names = set()
    for e in doc.get("event_alias", []):
        name = event_constant(e)
        if not name:
            problems.append(f"event entry with no constant: {e}")
        if name in names:
            problems.append(f"duplicate event constant {name}")
        names.add(name)
    if problems:
        for p in problems:
            print(f"error: {p}", file=sys.stderr)
        raise SystemExit(1)
    return doc


def load_catalog_events() -> list[str]:
    with EVENTS_SRC.open("rb") as fh:
        doc = tomllib.load(fh)
    names = []
    seen = set()
    for e in doc.get("event", []):
        n = e.get("lua_name")
        if n and n not in seen:
            seen.add(n)
            names.append(n)
    return names


def flatten_events(doc: dict) -> list[dict]:
    events = []
    mapped = set()
    for e in doc.get("event_alias", []):
        name = event_constant(e)
        events.append({
            "name": name,
            "lua_name": e.get("lua_name") or "",
            "note": e.get("note") or "",
        })
        mapped.add(name)
        if e.get("lua_name"):
            mapped.add(e["lua_name"])
    for n in load_catalog_events():
        if n in mapped:
            continue
        events.append({"name": n, "lua_name": n, "note": ""})
    return events


def gen_aliases(doc: dict) -> str:
    out = [BANNER_ALIASES, "// clang-format off"]
    for a in doc["alias"]:
        out.append(f'{{"{a["alias"]}", "{a["canonical"]}", "{a["dialect"]}"}},')
    out.append("// clang-format on")
    return "\n".join(out) + "\n"


def gen_events(events: list[dict]) -> str:
    out = [BANNER_EVENTS, "// clang-format off"]
    for i, e in enumerate(events):
        note = (e.get("note") or "").replace('"', "'")
        out.append(f'{{"{e["name"]}", "{e["lua_name"]}", {i}, "{note}"}},')
    out.append("// clang-format on")
    return "\n".join(out) + "\n"


def gen_docs(doc: dict, events: list[dict]) -> str:
    aliases = doc["alias"]

    by_canon: dict[str, list[dict]] = {}
    for a in aliases:
        by_canon.setdefault(a["canonical"], []).append(a)

    examples = [n for n in (
        "OnTick", "OnConsoleCommand", "OnModuleLoad",
        "OnModulePlayerEnter", "OnCreatureDeath", "OnAreaEnter",
    ) if any(e["name"] == n for e in events)]

    L = ["# Odyssey names and callbacks", "",
         "Generated from `data/api_aliases.toml` and `data/events.toml`. "
         "Do not edit by hand.", "",
         "KOTOR is `CServerExoApp` in-process with one hardcoded client. "
         "The player is `CServerExoApp::GetFirstPCObject` / NWScript "
         "`GetFirstPC`, not a Halo slot id. An object is "
         "`CServerExoAppInternal::GetGameObject` / `CSWSPlayer::GetGameObject`, "
         "not `getobject`. A message is `SendMessageToPC`.", "",
         "Host functions use the names the C modules registered "
         "(`readbyte`, `registertimer`, `feedback`). Scripts may also write "
         "the underscored form. Both spellings are the same C function.", "",
         f"**{len(aliases)} aliases** over **{len(by_canon)} functions**.", "",
         "## Names", "",
         "| this runtime calls it | also accepts |",
         "|---|---|"]
    for canon in sorted(by_canon):
        alts = ", ".join(f"`{a['alias']}`" for a in by_canon[canon])
        L.append(f"| `{canon}` | {alts} |")

    L += ["", "## Events", "",
          "Define a global and it is found at load:", "",
          "```lua", "function OnTick(tick, relevant)", "    -- ...", "end", "```", "",
          "Or register a handler by name at runtime:", "",
          "```lua", "function OnScriptLoad(game, build)",
          '    register_callback(cb.OnTick, "my_tick")',
          '    register_callback(cb.OnModulePlayerEnter, "on_enter")',
          "end", "```", "",
          "A runtime registration wins over a same-named global. "
          "`unregister_callback(cb.OnTick)` removes it.", "",
          f"Every event in `data/events.toml` is a field on `cb` (and `events`) "
          f"with the same name — **{len(events)}** of them, taken from the "
          "decompiled dispatch. Common ones:", "",
          "| constant | raises |", "|---|---|"]
    for name in examples:
        L.append(f"| `cb.{name}` | `{name}` |")
    L.append("")
    return "\n".join(L)


def main() -> int:
    doc = load_aliases()
    events = flatten_events(doc)
    GEN.mkdir(parents=True, exist_ok=True)
    (GEN / "compat_aliases.inc").write_text(gen_aliases(doc))
    (GEN / "compat_events.inc").write_text(gen_events(events))
    DOCS.write_text(gen_docs(doc, events))

    mapped = sum(1 for e in events if e.get("lua_name"))
    canon = len({a["canonical"] for a in doc["alias"]})
    print(f"{len(doc['alias'])} aliases over {canon} functions, "
          f"{len(events)} event constants ({mapped} mapped) "
          f"-> compat_aliases.inc, compat_events.inc, docs/api-dialects.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
