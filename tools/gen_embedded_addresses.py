#!/usr/bin/env python3
"""Embed data/addresses/*.json into src/generated/embedded_addresses.inc.

Used as a fallback by Runtime::resolve() when ScriptForge is loaded without an
extracted data/addresses/ directory on disk (for instance via a KPM .kpatch).
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ADDR_DIR = ROOT / "data/addresses"
OUT_PATH = ROOT / "src/generated/embedded_addresses.inc"


def platform_group(build: str) -> str:
    if "_mac_" in build:
        return "apple"
    if "_linux" in build:
        return "linux"
    return "win32"


def ident(build: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", build)


def emit_array(name: str, payload: bytes) -> list[str]:
    lines = [f"static constexpr unsigned char {name}[] = {{"]
    for off in range(0, len(payload), 24):
        chunk = payload[off : off + 24]
        lines.append("    " + ",".join(str(b) for b in chunk) + ",")
    lines.append("};")
    return lines


def generate() -> str:
    files = sorted(ADDR_DIR.glob("*.json"))
    if not files:
        raise RuntimeError(f"no address JSON files found in {ADDR_DIR}")

    groups: dict[str, list[tuple[str, bytes]]] = {"win32": [], "apple": [], "linux": []}
    for path in files:
        build = path.stem
        groups[platform_group(build)].append((build, path.read_bytes()))

    out: list[str] = [
        "// Generated by tools/gen_embedded_addresses.py. Do not edit; regenerate.",
        "// clang-format off",
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <string_view>",
        "",
        "namespace kp::generated {",
        "",
        "struct EmbeddedAddressEntry {",
        "    std::string_view build;",
        "    const unsigned char* data;",
        "    std::size_t size;",
        "};",
        "",
    ]

    def emit_table(entries: list[tuple[str, bytes]]) -> None:
        if not entries:
            out.append("inline constexpr EmbeddedAddressEntry kEmbeddedAddressTables[] = {};")
            out.append("inline constexpr std::size_t kEmbeddedAddressTableCount = 0;")
            return
        for build, data in entries:
            out.extend(emit_array(f"kEmbeddedAddr_{ident(build)}", data))
        out.append("inline constexpr EmbeddedAddressEntry kEmbeddedAddressTables[] = {")
        for build, _ in entries:
            arr = f"kEmbeddedAddr_{ident(build)}"
            out.append(f'    {{"{build}", {arr}, sizeof({arr})}},')
        out.append("};")
        out.append(
            "inline constexpr std::size_t kEmbeddedAddressTableCount = "
            "sizeof(kEmbeddedAddressTables) / sizeof(kEmbeddedAddressTables[0]);"
        )

    out.append("#if defined(_WIN32)")
    emit_table(groups["win32"])
    out.append("#elif defined(__APPLE__)")
    emit_table(groups["apple"])
    out.append("#else")
    emit_table(groups["linux"])
    out.append("#endif")
    out.extend([
        "",
        "inline std::string_view find_embedded_address_table(std::string_view build) {",
        "    for (std::size_t i = 0; i < kEmbeddedAddressTableCount; ++i) {",
        "        if (kEmbeddedAddressTables[i].build == build) {",
        "            return std::string_view(",
        "                reinterpret_cast<const char*>(kEmbeddedAddressTables[i].data),",
        "                kEmbeddedAddressTables[i].size);",
        "        }",
        "    }",
        "    return {};",
        "}",
        "",
        "}  // namespace kp::generated",
        "// clang-format on",
        "",
    ])
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="verify generated file matches disk without writing")
    args = ap.parse_args(argv)

    rendered = generate()
    if args.check:
        if not OUT_PATH.is_file():
            print(f"missing {OUT_PATH}", file=sys.stderr)
            return 1
        current = OUT_PATH.read_text(encoding="utf-8")
        if current != rendered:
            print(f"stale {OUT_PATH}; run python3 tools/gen_embedded_addresses.py", file=sys.stderr)
            return 1
        print(f"OK: {OUT_PATH} is up to date")
        return 0

    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text(rendered, encoding="utf-8")
    print(f"wrote {OUT_PATH} ({len(rendered)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
