#!/usr/bin/env python3
"""Generate the dispatcher glue and the Lua reference from data/events.toml.

Three artifacts come out of one input, on purpose:

  src/generated/callbacks.inc   the callback name list
  src/generated/events.inc      the contract table the dispatcher walks
  docs/lua-api.md               what script authors read

The list and the dispatcher must agree exactly. The design this project follows
shipped a bug where an event was dispatched but omitted from its equivalent of
callbacks.inc, so every script that did not define that event threw an error on
every single call. Generating both from the same rows removes the possibility
rather than relying on someone noticing.

Usage:
    ./gen_event_glue.py            # write all three
    ./gen_event_glue.py --check    # verify they are up to date, write nothing
"""
from __future__ import annotations

import argparse
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EVENTS = ROOT / "data" / "events.toml"
GEN = ROOT / "src" / "generated"
DOCS = ROOT / "docs" / "lua-api.md"

TYPE_ENUM = {
    "bool": "Bool", "int": "Int", "float": "Float",
    "string": "String", "object": "Object",
}
FALLBACK_ENUM = {
    "true": "True", "false": "False", "identity": "Identity", "none": "None",
}
BANNER = "// Generated by tools/gen_event_glue.py from data/events.toml.\n// Do not edit; edit the table and regenerate.\n"


def load() -> list[dict]:
    with EVENTS.open("rb") as fh:
        doc = tomllib.load(fh)
    events = doc.get("event", [])

    seen, problems = set(), []
    for e in events:
        for field in ("lua_name", "hook_site", "returns", "fallback",
                      "blocking", "engine_return"):
            if field not in e:
                problems.append(f"{e.get('lua_name', '?')}: missing {field}")
        name = e.get("lua_name")
        if name in seen:
            problems.append(f"{name}: duplicate lua_name")
        seen.add(name)
        for a in e.get("args", []):
            if a.get("type") not in TYPE_ENUM:
                problems.append(f"{name}: arg {a.get('name')} has unknown type {a.get('type')!r}")
        for r in e.get("returns", []):
            if r not in TYPE_ENUM:
                problems.append(f"{name}: unknown return type {r!r}")
        if e.get("fallback") not in FALLBACK_ENUM:
            problems.append(f"{name}: unknown fallback {e.get('fallback')!r}")
        # An event that cannot be claimed cannot have a meaningful fallback, and
        # an event that blocks must say what the engine is told.
        if e.get("blocking") and e.get("engine_return") == "Passthrough":
            problems.append(f"{name}: blocking but engine_return is Passthrough")
        if not e.get("returns") and e.get("blocking"):
            problems.append(f"{name}: blocking but returns nothing to block with")
    if problems:
        for p in problems:
            print(f"error: {p}", file=sys.stderr)
        raise SystemExit(1)
    return events


def gen_callbacks(events: list[dict]) -> str:
    lines = [BANNER]
    for e in events:
        lines.append(f'"{e["lua_name"]}",')
    return "\n".join(lines) + "\n"


def gen_events(events: list[dict]) -> str:
    out = [BANNER, "// clang-format off"]
    for e in events:
        args = ", ".join(
            '{{"{}", ValueType::{}, "{}"}}'.format(
                a["name"], TYPE_ENUM[a["type"]], a.get("source", ""))
            for a in e.get("args", []))
        rets = ", ".join(f"ValueType::{TYPE_ENUM[r]}" for r in e["returns"])
        outer = e.get("outer_event_id")
        etype = e.get("event_type")
        outer_s = str(int(outer)) if outer is not None else "-1"
        etype_s = str(int(etype)) if etype is not None else "-1"
        out.append("{")
        out.append(f'  "{e["lua_name"]}", "{e["hook_site"]}",')
        out.append(f'  {{{args}}},')
        out.append(f'  {{{rets}}},')
        out.append(f'  Fallback::{FALLBACK_ENUM[e["fallback"]]},')
        out.append(f'  {"true" if e["blocking"] else "false"},')
        out.append(f'  EngineReturn::{e["engine_return"]},')
        out.append(f'  {outer_s}, {etype_s},')
        out.append("},")
    out.append("// clang-format on")
    return "\n".join(out) + "\n"


def gen_docs(events: list[dict]) -> str:
    by_conf = {"high": [], "medium": [], "low": []}
    for e in events:
        by_conf.setdefault(e.get("confidence", "low"), []).append(e)

    # The worked example is built from a real row, not typed out. A hand-written
    # sample drifts the moment an event is renamed, and it drifts in the one
    # artifact script authors actually copy from -- which is a quieter version
    # of the bug this whole generated-from-one-table arrangement exists to stop.
    sample = next((e for e in events if e["hook_site"] == "vm.run_script"
                   and e.get("blocking")), None) or events[0]
    sample_args = [a["name"] for a in sample.get("args", [])] + ["relevant"]
    sample_sig = f'function {sample["lua_name"]}({", ".join(sample_args)})'
    first_arg = sample_args[0] if sample_args else "arg"

    L = ["# Lua API reference", "",
         "Generated from `data/events.toml`. Do not edit by hand.", "",
         "## How to write a script", "",
         "Define only the callbacks you want. Anything you leave out costs nothing.",
         "", "```lua", "priority = 10   -- optional; higher runs first, ties break on filename",
         "", sample_sig,
         f'    if {first_arg} == "k_def_heartbeat01" then return false end',
         "end", "```", "",
         "The trailing `relevant` argument always comes last, after every argument",
         "the event declares. It is false when another script has already decided",
         "the outcome.", "",
         "## When several scripts answer the same event", "",
         "Every script that defines the callback is called, in priority order. The first",
         "one to return a usable value decides the outcome. Later scripts still run, and",
         "receive `relevant = false` to say their answer will not be used.", "",
         "Returning nothing means you are abstaining, not voting. So does returning a",
         "value that will not convert -- a non-numeric string where a number is wanted,",
         "for instance. Returning `\"5\"` where a number is wanted does convert.", "",
         "For a boolean result the value is compared against 1. Returning `2` gives",
         "`false`, not `true`.", "",
         "If your event returns several values and any one of them will not convert, the",
         "whole answer is discarded and you have abstained.", "",
         "## Events", ""]

    for conf in ("high", "medium", "low"):
        group = by_conf.get(conf) or []
        if not group:
            continue
        if conf != "high":
            L += [f"### {conf.title()} confidence", "",
                  {"medium": "Argument mapping is partly verified. Check before relying on it.",
                   "low": "Argument mapping is **not yet verified against the game's own code**. "
                          "Names and types may change."}[conf], ""]
        for e in group:
            args = ", ".join(a["name"] for a in e.get("args", [])) or ""
            sig = f'{e["lua_name"]}({args}{", " if args else ""}relevant)'
            L.append(f"#### `{sig}`")
            L.append("")
            if e.get("doc"):
                L.append(" ".join(e["doc"].split()))
                L.append("")
            if e.get("args"):
                L.append("| argument | type | source |")
                L.append("|---|---|---|")
                for a in e["args"]:
                    src = a.get("source") or ""
                    L.append(f'| `{a["name"]}` | {a["type"]} | {src} |')
                L.append("")
            ret = ", ".join(e["returns"]) if e["returns"] else "nothing"
            L.append(f"Returns: {ret}. "
                     + (f"If no script answers, the result is `{e['fallback']}`. "
                        if e["fallback"] != "none" else "")
                     + ("Returning false stops the game's own handler."
                        if e["blocking"] else ""))
            L.append("")
    return "\n".join(L)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="fail if any output is stale; write nothing")
    args = ap.parse_args()

    events = load()
    outputs = {
        GEN / "callbacks.inc": gen_callbacks(events),
        GEN / "events.inc": gen_events(events),
        DOCS: gen_docs(events),
    }

    if args.check:
        stale = [p for p, text in outputs.items()
                 if not p.exists() or p.read_text() != text]
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)}", file=sys.stderr)
        return 1 if stale else 0

    GEN.mkdir(parents=True, exist_ok=True)
    for p, text in outputs.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
    conf = {}
    for e in events:
        conf[e.get("confidence", "low")] = conf.get(e.get("confidence", "low"), 0) + 1
    print(f"{len(events)} events -> callbacks.inc, events.inc, docs/lua-api.md")
    print("  confidence: " + ", ".join(f"{k} {v}" for k, v in sorted(conf.items())))
    return 0


if __name__ == "__main__":
    sys.exit(main())
