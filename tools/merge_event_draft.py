#!/usr/bin/env python3
"""Fold data/events.draft.toml into the canonical data/events.toml.

The draft is the output of reading the game's own decompiled event dispatch. It
uses a slightly different vocabulary, and two of its conventions have to be
translated rather than copied:

  `blocking` with no `returns`.  The draft means "the engine's call to this
      script can be suppressed, but the engine ignores whatever the script
      returned". Suppression is the only lever. In our model a script needs
      something to say no WITH, so those events take a bool: false suppresses.
      The fact that the engine discards its own return is recorded in the doc
      text rather than lost.

  `engine_return` as prose.  The draft explains what the engine does with the
      return; we need the enum saying what the engine is TOLD when Lua blocks.
      Blocking events report success, so suppression stays invisible to the
      caller -- see the note in events/contract.hpp.

Run after regenerating the draft; then run gen_event_glue.py.
"""
from __future__ import annotations

import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DRAFT = ROOT / "data" / "events.draft.toml"
OUT = ROOT / "data" / "events.toml"

# Events the runtime raises itself. They are not in the draft because they have
# no counterpart in the game's own dispatch.
RUNTIME_EVENTS = """
[[event]]
lua_name = "OnScriptLoad"
hook_site = "runtime"
args = [
  { name = "game",  type = "string" },
  { name = "build", type = "string" },
]
returns = []
fallback = "none"
blocking = false
engine_return = "Passthrough"
confidence = "high"
doc = "Called once after the script loads. `build` is the identified game build, e.g. k1_steam_103."

[[event]]
lua_name = "OnScriptUnload"
hook_site = "runtime"
args = []
returns = []
fallback = "none"
blocking = false
engine_return = "Passthrough"
confidence = "high"
doc = "Called before the script is unloaded, including on reload and on quarantine."

[[event]]
lua_name = "OnTick"
hook_site = "app.server_main_loop"
args = [{ name = "tick", type = "int" }]
returns = []
fallback = "none"
blocking = false
engine_return = "Passthrough"
confidence = "high"
doc = \"\"\"Called once per server frame. The highest-frequency callback: a script
that does not define it pays nothing, one that does should keep the body short.\"\"\"
"""

HEADER = '''# The event contract. One row per Lua callback.
#
# Generated by tools/merge_event_draft.py from data/events.draft.toml, which was
# derived by reading the game's own decompiled event dispatch. Edit the draft or
# the merge script, not this file.
#
# tools/gen_event_glue.py turns this into:
#   src/generated/callbacks.inc   the name list dispatch and the
#                                 undefined-callback probe both read
#   src/generated/events.inc      the contract table the dispatcher walks
#   docs/lua-api.md               the reference scripts are written against
#
# Two facts about this game worth knowing before reading further.
#
# Only ONE event's return value is consumed by the engine anywhere in the binary:
# the dialogue node conditional. Everywhere else the engine discards what the
# script returned, so a Lua handler's only real lever is suppression -- stopping
# the game's script from running at all. `returns = ["bool"]` on a blocking event
# means "false suppresses", not "this value reaches the engine".
#
# Event payloads are NOT fixed-size. Each of CScriptEvent's four parameter blocks
# is a CExoArrayList {void* data; int size; int capacity}, grown on demand. An
# earlier reading of this project treated them as three values each; indexing
# them that way reads the data POINTER as a value. Anything that reads a payload
# slot must go through the bounds-checked accessor.

[meta]
version = 2
game = "k1"
source = "data/events.draft.toml"
'''


def q(s: str) -> str:
    s = " ".join(str(s).split())
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main() -> int:
    if not DRAFT.exists():
        print(f"no draft at {DRAFT}", file=sys.stderr)
        return 1
    draft = tomllib.load(DRAFT.open("rb"))
    events = draft.get("event", [])

    out = [HEADER, RUNTIME_EVENTS.strip(), ""]
    seen = {"OnScriptLoad", "OnScriptUnload", "OnTick"}
    kept = skipped = 0

    for e in events:
        name = e.get("lua_name")
        if not name or name in seen:
            skipped += 1
            continue
        site = e.get("hook_site")
        if not site or site == "none":
            skipped += 1
            continue
        seen.add(name)
        kept += 1

        blocking = bool(e.get("blocking"))
        returns = [r for r in (e.get("returns") or []) if r in
                   ("bool", "int", "float", "string", "object")]
        if blocking and not returns:
            returns = ["bool"]
        fallback = e.get("fallback") or ("true" if blocking else "none")
        if fallback not in ("true", "false", "identity", "none"):
            fallback = "true" if blocking else "none"
        if not returns:
            fallback = "none"
        engine_return = "ReportSuccess" if blocking else "Passthrough"

        doc = " ".join(str(e.get("doc") or e.get("description") or "").split())
        extra = []
        if e.get("object_type") and e["object_type"] != "any":
            extra.append(f"Object type: {e['object_type']}.")
        if e.get("script_slot"):
            extra.append(f"Script slot: {e['script_slot']}.")
        if e.get("default_script"):
            extra.append(f"Default script: {e['default_script']}.")
        if blocking:
            extra.append("Return false to stop the game's own script running.")
        doc = " ".join(x for x in [doc] + extra if x).strip() or \
            f"Raised from {site}."

        out.append("[[event]]")
        out.append(f"lua_name = {q(name)}")
        out.append(f"hook_site = {q(site)}")
        args = []
        for a in e.get("args", []):
            t = a.get("type")
            if t not in ("bool", "int", "float", "string", "object"):
                continue
            src = f', source = {q(a["source"])}' if a.get("source") else ""
            args.append(f'  {{ name = {q(a["name"])}, type = {q(t)}{src} }},')
        if args:
            out.append("args = [")
            out.extend(args)
            out.append("]")
        else:
            out.append("args = []")
        out.append("returns = [" + ", ".join(q(r) for r in returns) + "]")
        out.append(f"fallback = {q(fallback)}")
        out.append(f"blocking = {'true' if blocking else 'false'}")
        out.append(f"engine_return = {q(engine_return)}")
        out.append(f"confidence = {q(e.get('confidence') or 'medium')}")
        out.append(f"doc = {q(doc)}")
        if e.get("evidence"):
            out.append(f"evidence = {q(e['evidence'])}")
        out.append("")

    OUT.write_text("\n".join(out))
    print(f"merged {kept} events ({skipped} skipped) -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
