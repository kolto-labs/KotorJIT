return function(test)
local function source(path,from,to)
 local h=assert(io.open('scripts/examples/'..path)); local s=h:read('*a'); h:close()
 local n; s,n=s:gsub(from,to); assert(n==1); return s
end
test('harness/10_world_probe.lua','world shape, sorted living hostiles and party',function(F,p)
 local f=F.new(p); f.area_objects={21,2,20}; f:load(); local r=f.result
 assert(r.pc.hp==100 and r.pc.x==0 and #r.hostiles==2 and r.hostiles[1].id==20)
 assert(#r.party==1 and r.party[1].id==2 and r.globals.END_ROOM3_DEAD==0)
 local g=F.new(p); g.objects[20].dead=1; g.objects[21].x=61; g:load(); assert(#g.result.hostiles==0)
end)
test('harness/20_dialog_state.lua','engine dialog shape and absent partner',function(F,p)
 local f=F.new(p):load(); assert(f.result.active==0 and f.result.pc_speaker=='pc' and f.result.partner_in==nil)
 local g=F.new(p); g.objects[2].tag='end_trask'; g:load(); assert(g.result.partner_dist==1 and g.result.partner_in==0)
end)
test('harness/30_move_to.lua','missing target errors, move request under PC',function(F,p)
 local f=F.new(p); assert(not pcall(function() f:load() end)); assert(f:count('ActionMoveToObject')==0)
 local g=F.new(p); g.objects[30].tag='end_door05'; g:load(); local c=g:last('ActionMoveToObject')
 assert(c.caller==1 and c.args[1]==30 and c.args[2]==1 and c.args[3]==1.5 and g.result.dist==2)
 local h=F.new(p):load(source(p,'local TARGET_TAG = "end_door05"','local TARGET_TAG = nil'))
 assert(h:last('ActionMoveToLocation').caller==1 and h:last('Vector').args[1]==-3)
end)
test('harness/40_attack_nearest.lua','nearest target, engagement and no enemies',function(F,p)
 local f=F.new(p):load(); local c=f:last('ActionAttack'); assert(c.args[1]==20 and c.args[2]==0 and c.caller==1 and f.result.queued)
 local g=F.new(p,{GetCurrentAction=function() return 39 end}):load(); assert(g.result.reason=='already engaged' and g:count('ActionAttack')==0)
 local h=F.new(p); h.area_objects={2}; h:load(); assert(h.result.reason=='no live hostile in radius')
end)
test('harness/50_doors.lua','inspect, self-open configuration and invalid door',function(F,p)
 local f=F.new(p); assert(not pcall(function() f:load() end))
 local g=F.new(p); g.objects[30].tag='end_door05'; g:load(); assert(g.result.open==0 and g:count('ActionOpenDoor')==0)
 local h=F.new(p); h.objects[30].tag='end_door05'; h:load(source(p,'local OPEN = false','local OPEN = true'))
 assert(h:last('ActionOpenDoor').caller==30 and h:last('ActionOpenDoor').args[1]==30 and h.result.queued)
end)
test('harness/60_area_dump.lua','typed sorted rows and empty area',function(F,p)
 local f=F.new(p):load(); assert(#f.result==3 and f.result[1].id==2 and f.result[2].hp==100 and f.result[2].hostile==1)
 local g=F.new(p); g.area_objects={}; g:load(); assert(#g.result==0)
end)
test('harness/70_pc_status.lua','status and populated equipment inventory effects',function(F,p)
 local f=F.new(p):load(); assert(f.result.hp==100 and #f.result.effects==0 and #f.result.inventory==0)
 local index=0
 local g=F.new(p,{GetFirstEffect=function() return 7 end,GetIsEffectValid=function(e) return e==7 and 1 or 0 end,
 GetNextEffect=function() return 0 end,GetEffectType=function() return 42 end,
 GetItemInSlot=function(slot) return slot==4 and 40 or F.INVALID end,
 GetFirstItemInInventory=function() return 40 end}):load()
 assert(g.result.effects[1]==42 and g.result.slots.slot4=='medpac' and g.result.inventory[1].id==40)
end)
test('harness/80_signal_event.lua','area and tag requests with missing target rejection',function(F,p)
 local f=F.new(p):load(); local c=f:last('SignalEvent'); assert(c.args[1]==99 and c.args[2].event==20 and f.result.id==99)
 local g=F.new(p):load(source(p,'local TARGET = "area"','local TARGET = "bastila"')); assert(g:last('SignalEvent').args[1]==2)
 local h=F.new(p); assert(not pcall(function() h:load(source(p,'local TARGET = "area"','local TARGET = "absent"')) end)); assert(h:count('SignalEvent')==0)
end)
test('harness/90_run_script.lua','authored script and selected self; invalid target rejected',function(F,p)
 local f=F.new(p); assert(not pcall(function() f:load() end)); assert(f:count('ExecuteScript')==0)
 local g=F.new(p); g.objects[30].tag='end_door08'; g:load(); local c=g:last('ExecuteScript')
 assert(c.args[1]=='k_pend_door20' and c.args[2]==30 and g.result.id==30)
end)
test('harness/100_module_transition.lua','inspect default and explicit configured request only',function(F,p)
 local f=F.new(p):load(); assert(f.result.module_now=='danm13' and f.result.door_valid==0 and f:count('StartNewModule')==0)
 local g=F.new(p):load(source(p,'local INSPECT = true','local INSPECT = false')); local c=g:last('StartNewModule')
 assert(c.args[1]=='end_m01ab' and c.args[2]=='from_01a' and g.result.requested=='end_m01ab/from_01a')
end)
test('harness/110_loot_container.lua','nearest stocked selection and PC-scoped takes',function(F,p)
 local f=F.new(p):load(); assert(f.result.taken==0 and f:count('ActionTakeItem')==0)
 local g=F.new(p); g.area_objects={30}; g:load(); local c=g:last('ActionTakeItem')
 assert(g.result.taken==1 and g.result.container==30 and c.caller==1 and c.args[1]==40 and c.args[2]==30)
end)
test('harness/40_attack_nearest.lua','inclusive radius and just-outside rejection',function(F,p)
 for _,distance in ipairs({40,40.5,41}) do
  local f=F.new(p); f.area_objects={20}; f.objects[20].x=distance; f:load()
  assert(f:count('ActionAttack')==(distance<=40 and 1 or 0))
 end
end)

end
