#!/usr/bin/env python3
"""Recover the VALUES of defaulted engine-routine parameters.

Why this exists
===============
`src/generated/routines_<game>.inc` records only THAT a parameter has a default,
because that is all `kp::api::Param` can hold. But NWScript defaults are a
compiler feature, not an engine one: the compiler emits the default expression
at the call site, and the engine handler pops whatever its signature declares.

Two handlers, read out of the K1 binary, show the two behaviours:

    ExecuteCommandSuppressStatusSummaryEntry   pops its one int unconditionally
    ExecuteCommandCreateItemOnObject           `cmp [esp+0x3c],0x3` -- it checks
                                               paramCount before the third pop

So a bridge that pushes only what the script supplied would, for every handler of
the first kind, make the routine pop whatever happened to be underneath. The
bridge therefore always pushes the full declared parameter count, which means it
needs the default VALUE, not just its existence.

Source of truth
===============
`data/routines/<game>.json` already carries each default as the expression text
the header wrote (`TRUE`, `OBJECT_SELF`, `-1`, `"" `, `[0.0,0.0,0.0]`). The named
constants are declared in the game's own `nwscript.nss` as ordinary globals
(`int TRUE = 1;`), so they resolve from the same file the signatures came from.

`OBJECT_SELF` and `OBJECT_INVALID` are NOT declared there -- they are compiler
builtins -- so they do not resolve, and the bridge requires those arguments
rather than guessing. That is the intended outcome, not a gap to paper over.

Usage:
    ./gen_routine_defaults.py --game k1
    ./gen_routine_defaults.py --all
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import gen_routine_table  # noqa: E402  -- reuse its nwscript.nss discovery

ROUTINES = ROOT / "data" / "routines"
GEN = ROOT / "src" / "generated"

# `int TRUE = 1;` / `float PI = 3.141592;` / `string FOO = "bar";`
CONST_DECL = re.compile(
    r"^\s*(int|float|string|object)\s+([A-Za-z_]\w*)\s*=\s*([^;]+);")

# Types that can carry a default we know how to marshal. `object` is listed
# because the parser sees it, but every object default in both headers is
# OBJECT_SELF or OBJECT_INVALID, neither of which resolves.
KIND = {"int": "Int", "float": "Float", "string": "String", "vector": "Vector"}

BANNER = ("// Generated by tools/gen_routine_defaults.py from "
          "data/routines/{game}.json\n"
          "// and the game's own nwscript.nss. Do not edit; regenerate.\n")


def read_constants(path: Path) -> dict[str, str]:
    """Every `<type> NAME = <expr>;` global in the header, unresolved."""
    out: dict[str, str] = {}
    for line in path.read_text(encoding="latin-1").splitlines():
        m = CONST_DECL.match(line)
        if m:
            out[m.group(2)] = m.group(3).strip()
    return out


def resolve(expr: str, consts: dict[str, str], depth: int = 0):
    """Turn a default expression into ('int'|'float'|'string'|'vector', value).

    Returns None when the expression is not a literal and not a header
    constant. A constant may be defined in terms of another one
    (`int PLAYER_CHAR_IS_PC = TRUE;`), hence the recursion, and the depth cap
    stops a malformed header from looping.
    """
    if depth > 8:
        return None
    e = expr.strip()
    if not e:
        return None

    # A string literal, including the empty one.
    if len(e) >= 2 and e[0] == '"' and e[-1] == '"':
        return ("string", e[1:-1])

    # A vector literal: the K1 header writes [0.0,0.0,0.0].
    if e.startswith("[") and e.endswith("]"):
        parts = [p.strip() for p in e[1:-1].split(",")]
        if len(parts) != 3:
            return None
        vals = []
        for p in parts:
            r = resolve(p, consts, depth + 1)
            if r is None or r[0] not in ("int", "float"):
                return None
            vals.append(float(r[1]))
        return ("vector", vals)

    # A float literal. `1.0f`, `-30.0`, `3.141592`.
    if re.fullmatch(r"[+-]?(\d+\.\d*|\.\d+|\d+)[fF]", e) or \
       re.fullmatch(r"[+-]?(\d+\.\d*|\.\d+)", e):
        return ("float", float(e.rstrip("fF")))

    # An integer literal, decimal or hex.
    if re.fullmatch(r"[+-]?\d+", e):
        return ("int", int(e))
    if re.fullmatch(r"[+-]?0[xX][0-9a-fA-F]+", e):
        return ("int", int(e, 16))

    # A named constant from the header.
    if e in consts:
        return resolve(consts[e], consts, depth + 1)

    return None


def c_float(v: float) -> str:
    # 9 significant digits round-trips a binary32 exactly, and the `f` suffix
    # keeps the compiler from warning about a narrowing double initialiser.
    # The point is forced back in because "%.9g" % 1.0 is "1", and "1f" is not
    # a C++ literal -- it is a compile error in the generated file.
    text = f"{v:.9g}"
    if "." not in text and "e" not in text and "E" not in text:
        text += ".0"
    return text + "f"


def c_string(s: str) -> str:
    out = s.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{out}"'


def emit(game: str) -> tuple[int, int, list]:
    data = json.loads((ROUTINES / f"{game}.json").read_text())
    nss = gen_routine_table._nss(game)
    if nss is None:
        raise SystemExit(
            f"nwscript.nss for {game} not found.\n"
            f"Vendor it at data/nwscript/{game}/nwscript.nss, set "
            f"KP_NWSCRIPT_{game.upper()}, or install the game.")
    consts = read_constants(nss)

    rows, unresolved = [], []
    for r in data["routines"]:
        params = r["params"]
        if params is None or r["returns"] is None:
            continue
        for idx, p in enumerate(params):
            if not p["default"]:
                continue
            got = resolve(p["default"], consts)
            want = KIND.get(p["type"])
            if got is None or want is None:
                unresolved.append({"id": r["id"], "name": r["name"],
                                   "param": p["name"], "index": idx,
                                   "type": p["type"], "expr": p["default"]})
                continue

            # The header is loose about int-vs-float in a default: `float
            # fRange = 0` and `int nNth = 1` both occur. The PARAMETER's type
            # decides what gets pushed, so convert to it here rather than
            # letting the C++ side guess.
            kind, val = got
            if want == "Float" and kind in ("int", "float"):
                rows.append((r["id"], idx, "Float", c_float(float(val)), p))
            elif want == "Int" and kind in ("int", "float") and float(val) == int(val):
                rows.append((r["id"], idx, "Int", str(int(val)), p))
            elif want == "String" and kind == "string":
                rows.append((r["id"], idx, "String", c_string(val), p))
            elif want == "Vector" and kind == "vector":
                rows.append((r["id"], idx, "Vector",
                             ", ".join(c_float(v) for v in val), p))
            else:
                unresolved.append({"id": r["id"], "name": r["name"],
                                   "param": p["name"], "index": idx,
                                   "type": p["type"], "expr": p["default"]})

    # Sorted so the C++ side can binary-search on (routine, index).
    rows.sort(key=lambda t: (t[0], t[1]))

    lines = [BANNER.format(game=game), "// clang-format off",
             "static const ParamDefault kParamDefaults[] = {"]
    for rid, idx, kind, val, p in rows:
        if kind == "Int":
            init = f"{val}, 0.0f, 0.0f, 0.0f, nullptr"
        elif kind == "Float":
            init = f"0, {val}, 0.0f, 0.0f, nullptr"
        elif kind == "Vector":
            init = f"0, {val}, nullptr"
        else:
            init = f"0, 0.0f, 0.0f, 0.0f, {val}"
        lines.append(f"  {{{rid}, {idx}, DefaultKind::{kind}, {init}}},  "
                     f"// {p['name']} = {p['default']}")
    lines.append("};")
    lines.append("// clang-format on")

    GEN.mkdir(parents=True, exist_ok=True)
    (GEN / f"routine_defaults_{game}.inc").write_text("\n".join(lines) + "\n")

    print(f"{game}: {len(rows)} defaults recovered, {len(unresolved)} not")
    by_expr: dict[str, int] = {}
    for u in unresolved:
        by_expr[u["expr"]] = by_expr.get(u["expr"], 0) + 1
    for expr, n in sorted(by_expr.items(), key=lambda kv: -kv[1]):
        print(f"    unresolved: {expr}  x{n}")
    return len(rows), len(unresolved), unresolved


def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--game", choices=("k1", "k2"))
    ap.add_argument("--all", action="store_true")
    ap.add_argument("--list-unresolved", action="store_true",
                    help="print every routine that keeps a required argument")
    args = ap.parse_args()
    games = ["k1", "k2"] if args.all else ([args.game] if args.game else [])
    if not games:
        ap.error("pass --game or --all")

    for g in games:
        _, _, unresolved = emit(g)
        if args.list_unresolved:
            for u in unresolved:
                print(f"    {g} {u['id']:>4} {u['name']}({u['param']}) "
                      f"= {u['expr']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
