#!/usr/bin/env python3
"""Emit the C++ routine table and the Lua reference from data/routines/<game>.json.

Produces:
    src/generated/routines_<game>.inc    the kp::api::Routine table
    docs/nwscript-api.md                 the routine list script authors read

Routines whose signature the header never documented are skipped, with a count
reported. A routine we cannot describe cannot be marshalled -- we would not know
what to push -- and emitting it with a guessed signature would corrupt the VM
stack on the first call.

Usage:
    ./gen_routine_glue.py --game k1
    ./gen_routine_glue.py --all
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ROUTINES = ROOT / "data" / "routines"
GEN = ROOT / "src" / "generated"
DOCS = ROOT / "docs" / "nwscript-api.md"

# nwscript type -> kp::api::Type. `action` is void for marshalling purposes: it
# returns nothing, it just also queues an action.
TYPE = {
    "void": "Void", "int": "Int", "float": "Float", "string": "String",
    "object": "Object", "vector": "Vector", "effect": "Effect",
    "event": "Event", "location": "Location", "talent": "Talent",
    # The header is not consistent about case. SetAvailableNPCId is declared
    # `void SetAvailableNPCId(INT nNPC, OBJECT_ID oidNPC)`, which is the same
    # two types shouted. Dropping the routine over that would be silly.
    "INT": "Int", "OBJECT_ID": "Object",
}

# `action` is a script closure: the NWScript compiler emits STORE_STATE bytecode
# that captures a subroutine and its stack frame. There is no way to build one
# from outside the VM without synthesising bytecode, so AssignCommand,
# DelayCommand and ActionDoCommand cannot be called directly from Lua. Lua gets
# the same effect through the runtime's own scheduler instead -- see OnTick.
NEEDS_CLOSURE = {"action"}

# Every type is marshallable, but in three different ways, and the difference
# shows up in the Lua API:
#
#   scalars    int, float, string, object -- plain Lua values.
#   vector     three floats. Lua sees a table {x=, y=, z=}; the VM has dedicated
#              StackPush/PopVector calls, so this is not three int pushes.
#   engine     effect, event, location, talent -- opaque VM handles. Lua gets a
#     structs   userdata it can hold and pass back but not inspect. There are
#               exactly four; NWN's fifth (itemproperty) does not exist in KOTOR,
#               and pushing its type id would be rejected by the VM.
ENGINE_STRUCT_ID = {"Effect": 0, "Event": 1, "Location": 2, "Talent": 3}


def marshal_kind(t: str) -> str:
    if t in ENGINE_STRUCT_ID:
        return "engine_struct"
    if t == "Vector":
        return "vector"
    return "scalar"

BANNER = ("// Generated by tools/gen_routine_glue.py from data/routines/{game}.json.\n"
          "// Do not edit; regenerate.\n")


def emit(game: str) -> int:
    data = json.loads((ROUTINES / f"{game}.json").read_text())
    routines = data["routines"]

    ok, no_sig, unsupported = [], [], []
    kinds = {"scalar": 0, "vector": 0, "engine_struct": 0}
    for r in routines:
        if r["returns"] is None or r["params"] is None:
            no_sig.append(r)
            continue
        raw = [r["returns"]] + [p["type"] for p in r["params"]]
        if any(t in NEEDS_CLOSURE for t in raw):
            unsupported.append((r, "takes a script closure (action)"))
            continue
        types = [TYPE.get(t) for t in raw]
        if any(t is None for t in types):
            unsupported.append((r, "unknown type " +
                                ", ".join(t for t, m in zip(raw, types) if m is None)))
            continue
        worst = "scalar"
        for t in types:
            k = marshal_kind(t)
            if k == "engine_struct":
                worst = "engine_struct"
            elif k == "vector" and worst == "scalar":
                worst = "vector"
        kinds[worst] += 1
        ok.append(r)

    lines = [BANNER.format(game=game), "// clang-format off"]
    for r in ok:
        params = r["params"]
        required = sum(1 for p in params if not p["default"])
        if params:
            plist = ", ".join(
                f'{{Type::{TYPE[p["type"]]}, "{p["name"]}", {"true" if p["default"] else "false"}}}'
                for p in params)
            lines.append(f'static const Param kP_{r["id"]}[] = {{{plist}}};')
        else:
            lines.append(f'static const Param* const kP_{r["id"]} = nullptr;')
    lines.append("")
    lines.append("static const Routine kRoutines[] = {")
    for r in ok:
        n = len(r["params"])
        required = sum(1 for p in r["params"] if not p["default"])
        lines.append(f'  {{{r["id"]}, "{r["name"]}", Type::{TYPE[r["returns"]]}, '
                     f'kP_{r["id"]}, {n}, {required}}},')
    lines.append("};")
    lines.append("// clang-format on")

    GEN.mkdir(parents=True, exist_ok=True)
    (GEN / f"routines_{game}.inc").write_text("\n".join(lines) + "\n")

    print(f"{game}: {len(ok)} callable "
          f"(scalar {kinds['scalar']}, vector {kinds['vector']}, "
          f"engine-struct {kinds['engine_struct']}), "
          f"{len(unsupported)} unsupported, {len(no_sig)} undocumented "
          f"(total {len(routines)})")
    return len(ok), unsupported, no_sig, routines, kinds


def docs(results: dict) -> str:
    L = ["# NWScript routines from Lua", "",
         "Generated from `data/routines/`. Do not edit by hand.", "",
         "`nwscript.call(name, ...)` is the only direct engine-routine entry point.",
         "Routine names are catalog data, not Lua globals or table members:", "",
         "```lua", 'local m = nwscript.call("GetModule")',
         'local pc = nwscript.call("GetFirstPC")',
         'nwscript.call("SendMessageToPC", pc, "hello")', "```", "",
         "Arguments follow the declaration order in the game's own `nwscript.nss`.",
         "Defaulted parameters may be omitted from the right.", ""]
    for game, (n_ok, unsupported, no_sig, all_r, kinds) in results.items():
        L += [f"## {game.upper()}", "",
              f"- callable: **{n_ok}** of {len(all_r)}",
              f"  - plain values only: {kinds['scalar']}",
              f"  - take or return a vector: {kinds['vector']}",
              f"  - take or return an engine structure: {kinds['engine_struct']}",
              f"- unsupported: {len(unsupported)}",
              f"- declared by the binary but undocumented in the header: {len(no_sig)}",
              f"- total ids: {len(all_r)}", ""]
        L += ["A vector is a Lua table with `x`, `y`, and `z`. An `effect`,",
              "`event`, `location`, or `talent` is an opaque handle: hold it in a",
              "variable and pass it back to another routine, but do not expect to",
              "read fields off it.", ""]
        if unsupported:
            L += ["Not callable:", ""]
            for r, why in unsupported:
                L.append(f"- `{r['name']}` -- {why}")
            L += ["",
                  "`AssignCommand`, `DelayCommand`, and `ActionDoCommand` take a script",
                  "closure, which the NWScript compiler builds as bytecode. Lua cannot",
                  "hand one over. Use the runtime's own scheduler in `OnTick` for delayed",
                  "work instead.", ""]
        if no_sig:
            names = ", ".join(f"`{r['name']}`" for r in no_sig[:12])
            L += [f"Undocumented ids include {names}"
                  + (f", and {len(no_sig) - 12} more." if len(no_sig) > 12 else "."), ""]
    return "\n".join(L)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--game", choices=("k1", "k2"))
    ap.add_argument("--all", action="store_true")
    args = ap.parse_args()
    games = ["k1", "k2"] if args.all else ([args.game] if args.game else [])
    if not games:
        ap.error("pass --game or --all")

    results = {g: emit(g) for g in games}
    DOCS.write_text(docs(results))
    return 0


if __name__ == "__main__":
    sys.exit(main())
