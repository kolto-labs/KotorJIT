#!/usr/bin/env bash
# Regenerate src/proxy/binkw32.def from the games' own binkw32.dll.
#
# The .def is a list of export names, which is interoperability information
# rather than anything of RAD's we could copy. No Bink binary is redistributed;
# the proxy forwards to the original, renamed alongside it.
#
# Both games are read because K2's Aspyr build exports a slightly different set,
# and one proxy that carries the union serves both.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="${OUT:-$ROOT/src/proxy/binkw32.def}"

find_bink() {  # $1 = k1|k2
  local dir
  dir="$(python3 "$ROOT/tools/kpdiscover.py" "--$1" 2>/dev/null || true)"
  [[ -n "$dir" ]] || return 0
  # Case varies by platform and the file can sit one level up from the data dir.
  find "$dir" "$dir/.." -maxdepth 1 -iname "binkw32.dll" 2>/dev/null | head -1
}

K1="${K1_BINK:-$(find_bink k1)}"
K2="${K2_BINK:-$(find_bink k2)}"
[[ -n "$K1$K2" ]] || { echo "no game install found; set K1_BINK or K2_BINK" >&2; exit 1; }

command -v winedump >/dev/null || { echo "winedump not found (dnf install wine-core)" >&2; exit 1; }

names() {
  [[ -f "$1" ]] || return 0
  winedump -j export "$1" 2>/dev/null | grep -oE "_?Bink[A-Za-z0-9_]*@[0-9]+" || true
}

{
  echo "; Generated by scripts/gen_bink_def.sh from the games' own binkw32.dll."
  echo "; Export names only - an interoperability list, not RAD's code. No Bink"
  echo "; binary is redistributed; the original is renamed alongside this proxy."
  echo "LIBRARY binkw32"
  echo "EXPORTS"
  { names "$K1"; names "$K2"; } | sort -u |
    while read -r e; do printf "    %s = binkw32_real.%s\n" "$e" "$e"; done
} > "$OUT"

echo "wrote $OUT ($(grep -c binkw32_real "$OUT") exports)"
